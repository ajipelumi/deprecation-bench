# Helpers that exist for local inspection and have no caller in the notebook.
DROP_FUNCS = {"by_truth", "summary", "_run_tests", "_normalise_for_test"}


def _strip_main(src):
    i = src.find('if __name__ == "__main__":')
    return src[:i].rstrip() + "\n" if i != -1 else src


def _strip_docstring(src):
    return re.sub(r'^"""(.*?)"""\n', "", src, count=1, flags=re.S)


def _strip_tests(src):
    """Drop a trailing test section marked by a banner comment."""
    return re.sub(r"\n# -{10,}\n# Tests\..*", "\n", src, flags=re.S)


def _drop_funcs(src, names):
    """Remove whole top-level function defs by name, using the AST for bounds."""
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)
    cuts = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in names:
            start = node.lineno - 1
            # include any decorator lines above the def
            if node.decorator_list:
                start = min(d.lineno for d in node.decorator_list) - 1
            cuts.append((start, node.end_lineno))
    for start, end in sorted(cuts, reverse=True):
        del lines[start:end]
    return "".join(lines)


def _extract_imports(src):
    """Pull top-level imports out, returning (import_lines, remaining_source)."""
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)
    imports, cuts = [], []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            imports.append("".join(lines[node.lineno - 1:node.end_lineno]))
            cuts.append((node.lineno - 1, node.end_lineno))
    for start, end in sorted(cuts, reverse=True):
        del lines[start:end]
    return imports, "".join(lines)


def _strip_comments(src):
    """Drop standalone comment lines, keeping section banners and inline notes.

    The repo sources carry long explanations of why each decision was made; that
    belongs in review, not in a notebook cell someone is scrolling through. What
    survives: `# ---` banners, and short trailing comments on a line of code.
    Docstrings are untouched, so the reasoning that matters stays reachable.
    """
    out = []
    for line in src.splitlines(keepends=True):
        stripped = line.lstrip()
        if stripped.startswith("#"):
            body = stripped.lstrip("#").strip()
            if set(body) <= {"-"} and body:      # banner rule
                out.append(line)
            elif body.isupper() and len(body) < 40:   # banner label
                out.append(line)
            continue
        out.append(line)
    return "".join(out)


def _tidy(src):
    """Collapse runs of blank lines left behind by the cuts above."""
    src = re.sub(r"\n{4,}", "\n\n\n", src)
    src = re.sub(r"(\n\s*\n)+(\s*\))", r"\n\2", src)
    return src.strip() + "\n"


def build():
    items = _strip_docstring(_strip_main((HERE / "items.py").read_text(encoding="utf-8")))
    classify = _strip_docstring(_strip_main((HERE / "classify.py").read_text(encoding="utf-8")))
    task = _strip_docstring((HERE / "task.py").read_text(encoding="utf-8"))

    classify = _strip_tests(classify)

    # Cross-module imports collapse to one namespace in a notebook, and the
    # sys.path juggling only matters when running the files locally.
    task = re.sub(r"from classify import \([^)]*\)[^\n]*\n", "", task)
    task = re.sub(r"from items import ITEMS[^\n]*\n", "", task)
    task = re.sub(r"sys\.path\.insert\([^\n]*\n", "", task)

    # task.py ends with its own .run() so it is executable standalone. The
    # notebook appends its own runner, and leaving both in means every
    # benchmark executes twice and bills twice.
    task, n = re.subn(r"\n\w[\w.]*\.run\(llm=[^\n]*\)\n*$", "\n", task)
    if n != 1:
        raise SystemExit(
            f"expected exactly one trailing .run() in task.py, stripped {n}. "
            "Check the tail of task.py before generating."
        )

    items = _drop_funcs(items, DROP_FUNCS)
    classify = _drop_funcs(classify, DROP_FUNCS)
    task = _drop_funcs(task, DROP_FUNCS)

    parts, all_imports = [], []
    for label, src in (("GROUND TRUTH", items),
                       ("CLASSIFIER", classify),
                       ("TASK", task)):
        imps, body = _extract_imports(src)
        all_imports.extend(imps)
        parts.append((label, _tidy(_strip_comments(body))))

    # json is used by the runner appended below; everything else comes from the
    # sources. Dedupe while keeping a stable order: stdlib, then third party.
    all_imports.append("import json\n")
    seen, deduped = set(), []
    for line in all_imports:
        key = line.strip()
        if key and key not in seen:
            seen.add(key)
            deduped.append(line)

    # Drop imports nothing in the assembled notebook uses. `sys` and `os` are
    # only there for the local sys.path plumbing that gets stripped above.
    body_text = "".join(body for _, body in parts) + RUNNER

    def _used(import_line):
        names = []
        for node in ast.parse(import_line).body:
            for alias in node.names:
                names.append(alias.asname or alias.name.split(".")[0])
        return any(re.search(rf"\b{re.escape(n)}\b", body_text) for n in names)

    deduped = [i for i in deduped if _used(i)]

    third_party = [i for i in deduped if "kaggle_benchmarks" in i]
    stdlib = [i for i in deduped if "kaggle_benchmarks" not in i]
    import_block = "".join(sorted(stdlib)) + "\n" + "".join(third_party)

    out = [HEADER, "\n", import_block]
    for label, body in parts:
        out.append(f"\n\n# {'-' * 74}\n# {label}\n# {'-' * 74}\n\n")
        out.append(body)
    out.append(RUNNER)

    text = "".join(out)
    ast.parse(text)  # fail here rather than in the notebook

    # A second .run() would double every benchmark's cost, silently.
    runs = len(re.findall(r"^(?:\w+\s*=\s*)?\w[\w.]*\.run\(", text, re.M))
    if runs != 1:
        raise SystemExit(f"notebook contains {runs} top-level .run() calls, expected 1")

    return text


def main():
    text = build()
    check = "--check" in sys.argv

    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("notebook_cell.py is stale. Run: python build_notebook.py")
            diff = difflib.unified_diff(
                current.splitlines(), text.splitlines(),
                "current", "generated", lineterm="", n=1,
            )
            for line in list(diff)[:40]:
                print(line)
            return 1
        print("notebook_cell.py is up to date")
        return 0

    OUT.write_text(text, encoding="utf-8")
    tree = ast.parse(text)
    imports = sum(isinstance(n, (ast.Import, ast.ImportFrom)) for n in tree.body)
    print(f"wrote {OUT.name}: {text.count(chr(10))} lines, {imports} imports")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
