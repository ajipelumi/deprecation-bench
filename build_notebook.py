"""Assemble the single-cell notebook file from the three source modules.

Kaggle wants one cell; the repo wants testable modules. This bridges them, and
having it as a script rather than an ad-hoc command means the notebook never
drifts from the sources it was built from.

What gets dropped on the way in:

- module docstrings (the notebook gets one header of its own)
- `if __name__ == "__main__"` blocks (self-tests belong in the repo)
- test suites and fixtures
- local-only import plumbing (`sys.path` juggling, cross-module imports that
  are a single namespace in a notebook)
- helpers nothing in the notebook calls

Imports are hoisted to the top and de-duplicated, so the output has one import
block rather than one per source file.

Run `python build_notebook.py` after touching items.py, classify.py or task.py,
then `python build_notebook.py --check` in CI or before a commit to confirm the
generated file is current.
"""

